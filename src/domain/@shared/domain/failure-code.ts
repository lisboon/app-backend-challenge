export const FailureKind = {
  CONTRACT: 'CONTRACT',
  CONFLICT: 'CONFLICT',
  NOT_FOUND: 'NOT_FOUND',
  BUSINESS: 'BUSINESS',
} as const;

export type FailureKind = (typeof FailureKind)[keyof typeof FailureKind];

const KIND_BY_CODE: Readonly<Record<FailureCode, FailureKind>> = {
  [FailureCode.MONEY_INVALID_FORMAT]: FailureKind.CONTRACT,
  [FailureCode.MONEY_OUT_OF_RANGE]: FailureKind.CONTRACT,
  [FailureCode.CURRENCY_INVALID]: FailureKind.CONTRACT,
  [FailureCode.CURRENCY_MISMATCH]: FailureKind.CONTRACT,

  [FailureCode.IDEMPOTENCY_PAYLOAD_CONFLICT]: FailureKind.CONFLICT,
  [FailureCode.WALLET_ALREADY_EXISTS]: FailureKind.CONFLICT,
  [FailureCode.TRANSACTION_ALREADY_TERMINAL]: FailureKind.CONFLICT,

  [FailureCode.WALLET_NOT_FOUND]: FailureKind.NOT_FOUND,
  [FailureCode.REFERENCE_NOT_FOUND]: FailureKind.NOT_FOUND,

  [FailureCode.INSUFFICIENT_BALANCE]: FailureKind.BUSINESS,
  [FailureCode.REVERSAL_WOULD_OVERDRAW]: FailureKind.BUSINESS,
  [FailureCode.REFERENCE_MISMATCH]: FailureKind.BUSINESS,
  [FailureCode.REFERENCE_ALREADY_REVERSED]: FailureKind.BUSINESS,
  [FailureCode.REFERENCE_KIND_NOT_REVERSIBLE]: FailureKind.BUSINESS,
  [FailureCode.REVERSAL_AMOUNT_MISMATCH]: FailureKind.BUSINESS,
  [FailureCode.TRANSACTION_KIND_NOT_SUBMITTABLE]: FailureKind.BUSINESS,
};

export function failureKindOf(code: FailureCode): FailureKind {
  return KIND_BY_CODE[code];
}
